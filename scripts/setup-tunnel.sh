# STAGES: one stage() per step the human takes.
# ──────────────────────────────────────────────────────────────────────────

TOTAL_STAGES=9

NAME=nico-agent-tunnel
TUNNEL=nico-agent
PORT=42069 # serve's, http::PORT
CF_DIR="$HOME/.cloudflared"
ENV_FILE="$CF_DIR/nico-agent.env" # the hostname and email, offered again on a re-run
creds="$CF_DIR/nico-agent.json"
ingress="$CF_DIR/nico-agent.yml"
service_file="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user/$NAME.service"
config="$HOME/.config/nico-agent/config.toml"
bin="${NICO_AGENT_BIN:-$(command -v nico-agent || echo "$HOME/.local/bin/nico-agent")}"

# ask_valid KEY "Prompt" REGEX "what a good answer is": ask until the answer
# matches; stdin ending stops the wizard.
ask_valid() {
  while ask "$1" "$2"; do
    [[ "${!1}" =~ $3 ]] && return 0
    warn "$4"
  done
  exit 1
}

# put FILE CONTENT: write FILE after a yes, unless it holds CONTENT already;
# changed=1 when written.
put() {
  if [[ -f "$1" && "$(cat "$1")" == "$2" ]]; then
    note "unchanged: $1"
    return
  fi
  say "will write $1:"
  printf '%s\n' "$2" | sed 's/^/      /'
  confirm "Write it?" || { say "left as is"; exit 0; }
  mkdir -p "$(dirname "$1")"
  printf '%s\n' "$2" >"$1"
  changed=1
  printf '  %s✓ wrote%s %s\n' "$GREEN" "$RESET" "$1"
}

# with_url FILE URL: FILE with url = "URL" in its [bucket] table and every
# other line as it was. An url line there is replaced, else one goes under
# the header, else a [bucket] table is added at the end.
with_url() {
  local file="$1"
  [[ -f "$file" ]] || file=/dev/null
  awk -v line="url = \"$2\"" '
    function header() { return /^[[:space:]]*\[/ }
    function bucket() { return /^[[:space:]]*\[[[:space:]]*bucket[[:space:]]*\][[:space:]]*(#.*)?$/ }
    function url() { return /^[[:space:]]*url[[:space:]]*=/ }
    NR == FNR { if (header()) { first = bucket(); seen = seen || first } else if (first && url()) has = 1; next }
    header() { inside = bucket(); print; if (inside && !has) print line; next }
    inside && url() { print line; next }
    { print }
    END { if (!seen) { if (FNR) print ""; print "[bucket]"; print line } }
  ' "$file" "$file"
}

banner "nico-agent tunnel: serve, for you only, from anywhere"

stage "cloudflared"
cloudflared=$(command -v cloudflared || true)
if [[ -z "$cloudflared" && -x "$HOME/.local/bin/cloudflared" ]]; then
  cloudflared="$HOME/.local/bin/cloudflared"
fi
if [[ -z "$cloudflared" ]]; then
  case "$(uname -m)" in
    x86_64) arch=amd64 ;;
    aarch64 | arm64) arch=arm64 ;;
    *) arch="" ;;
  esac
  release="https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-linux-$arch"
  say "cloudflared is not installed."
  if [[ -z "$arch" ]] || ! confirm "Download $release to ~/.local/bin/cloudflared?"; then
    say "Install it from https://developers.cloudflare.com/cloudflare-one/networks/connectors/cloudflare-tunnel/downloads/"
    say "and run this again."
    exit 1
  fi
  mkdir -p "$HOME/.local/bin"
  curl -fL --progress-bar -o "$HOME/.local/bin/cloudflared.tmp" "$release"
  chmod +x "$HOME/.local/bin/cloudflared.tmp"
  mv "$HOME/.local/bin/cloudflared.tmp" "$HOME/.local/bin/cloudflared"
  cloudflared="$HOME/.local/bin/cloudflared"
fi
say "Using $cloudflared: $("$cloudflared" --version)"
pause

stage "Log in to Cloudflare"
if [[ -f "$CF_DIR/cert.pem" ]]; then
  say "Logged in already: $CF_DIR/cert.pem is there."
  note "It holds the zone (domain) picked at login, and the hostname must be in it."
  note "For a hostname in another zone, move cert.pem aside and run this again."
  pause
else
  say "cloudflared opens a Cloudflare page: log in, pick the zone (domain) the"
  say "hostname will live in, and Authorize. It saves $CF_DIR/cert.pem."
  pause "Press Enter to run: cloudflared tunnel login"
  "$cloudflared" tunnel login
  [[ -f "$CF_DIR/cert.pem" ]] || { warn "no $CF_DIR/cert.pem: run this again to log in"; exit 1; }
fi

stage "Hostname and email"
say "The app and the Bucket will be at https://<hostname>/, behind an Access"
say "login that only your email passes."
ask_valid TUNNEL_HOST "Hostname, in that zone (e.g. nico.example.com):" \
  '^[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$' "a bare hostname: no https://, no path"
ask_valid ACCESS_EMAIL "Your email, the only one Access lets in:" \
  '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' "an email address"
mkdir -p "$CF_DIR"
write_env TUNNEL_HOST "$TUNNEL_HOST"
write_env ACCESS_EMAIL "$ACCESS_EMAIL"

stage "Create the tunnel"
if [[ -f "$creds" ]]; then
  say "The tunnel $TUNNEL is there: its credentials are in $creds."
else
  say "This creates the tunnel $TUNNEL in your Cloudflare account and saves its"
  say "credentials to $creds."
  confirm "Create it?" || { say "left as is"; exit 0; }
  if ! "$cloudflared" tunnel create --cred-file "$creds" "$TUNNEL"; then
    warn "If a tunnel named $TUNNEL exists already, its credentials are not here:"
    say "delete it (cloudflared tunnel delete $TUNNEL) and run this again."
    exit 1
  fi
fi
tunnel_id=$(grep -oE '[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}' "$creds" | head -n1 || true)
[[ -n "$tunnel_id" ]] || { warn "no tunnel id in $creds"; exit 1; }
say "Tunnel id: $tunnel_id"
pause

stage "Cloudflare Access: you only"
say "serve has no login of its own, so Access is the lock. It goes in front"
say "before the hostname points anywhere."
open_url "https://one.dash.cloudflare.com/"
step "Integrations → Identity providers: if One-time PIN is not listed, Add new identity provider → One-time PIN."
step "Access controls → Applications → Create new application → Self-hosted and private."
step "Name it nico-agent. Add public hostname: the subdomain and domain that make $TUNNEL_HOST."
step "Access policies: one policy, Action Allow, Include → Emails → $ACCESS_EMAIL, and no other rule."
step "Login methods: One-time PIN. Then Create."
note "Menus moved? https://developers.cloudflare.com/cloudflare-one/access-controls/applications/http-apps/self-hosted-public-app/"
pause "Press Enter once the application is created"

stage "The tunnel as a service"
ingress_text=$(
  cat <<EOF
tunnel: $tunnel_id
credentials-file: $creds
ingress:
  - hostname: $TUNNEL_HOST
    service: http://127.0.0.1:$PORT
  - service: http_status:404
EOF
)
# Its own --config: ~/.cloudflared/config.yml may be another tunnel's.
service=$(
  cat <<EOF
[Unit]
Description=nico-agent tunnel: serve behind Cloudflare Access

[Service]
Type=simple
ExecStart=$cloudflared tunnel --no-autoupdate --config $ingress run
Restart=always
RestartSec=5s

[Install]
WantedBy=default.target
EOF
)
changed=0
put "$ingress" "$ingress_text"
put "$service_file" "$service"
if [[ $changed -eq 1 ]]; then
  systemctl --user daemon-reload
fi
if confirm "Enable and (re)start $NAME.service?"; then
  systemctl --user enable "$NAME.service"
  systemctl --user restart "$NAME.service"
  note "its log: journalctl --user -u $NAME.service"
else
  SKIPPED+=("start the tunnel: systemctl --user enable --now $NAME.service")
fi

stage "Point $TUNNEL_HOST at the tunnel"
say "This adds the DNS record that makes $TUNNEL_HOST answer, behind Access."
confirm "Route $TUNNEL_HOST to the tunnel?" || { say "left as is"; exit 0; }
if ! "$cloudflared" tunnel route dns "$tunnel_id" "$TUNNEL_HOST"; then
  warn "$TUNNEL_HOST has a DNS record that points elsewhere."
  confirm "Overwrite it to point at the tunnel?" || exit 1
  "$cloudflared" tunnel route dns --overwrite-dns "$tunnel_id" "$TUNNEL_HOST"
fi
answer=$(curl -s -o /dev/null --max-time 20 -H 'Accept: text/html' -w '%{http_code} %{redirect_url}' "https://$TUNNEL_HOST/" || true)
case "$answer" in
  30[1237]\ https://*.cloudflareaccess.com/*)
    printf '  %s✓%s a stranger at %s is sent to the Access login\n' "$GREEN" "$RESET" "$TUNNEL_HOST"
    ;;
  "000 "* | "")
    warn "$TUNNEL_HOST does not answer yet (new DNS can take minutes); the phone check covers it."
    ;;
  *)
    systemctl --user stop "$NAME.service"
    warn "$TUNNEL_HOST answered \"$answer\", not with the Access login, so the tunnel is stopped."
    say "Make the Access application's hostname exactly $TUNNEL_HOST and run this again."
    exit 1
    ;;
esac
pause

stage "Check from your phone"
step "On your phone, open https://$TUNNEL_HOST/ and sign in: $ACCESS_EMAIL, Send login code, the code from your inbox."
note "serve answers with the page (until the app ships, with a JSON list of its routes)."
note "A Cloudflare error page instead means serve is down: scripts/install-service.sh"
step "Open https://$TUNNEL_HOST/bucket/README.md: the Bucket's README."
pause "Press Enter once both opened"
step "In a private window, open https://$TUNNEL_HOST/ and sign in with a second email you can read."
note "Access always says \"A code has been emailed to you\"; to an email it refuses, none is sent."
step "Wait two minutes and look in that inbox, spam included."
if ! confirm "Did $ACCESS_EMAIL get in, and the second email get no code?"; then
  systemctl --user stop "$NAME.service"
  warn "Stopped $NAME.service. Make the policy Include → Emails → $ACCESS_EMAIL alone, then run this again."
  exit 1
fi

stage "Evidence links through the tunnel"
url="https://$TUNNEL_HOST"
# bucket::url adds /bucket/<owner>/<repo>/<issue>/ to it.
say "bucket.url in $config becomes $url: the implement prompt then links"
say "Evidence at $url/bucket/<owner>/<repo>/<issue>/."
mkdir -p "$(dirname "$config")"
if grep -qE '^[[:space:]]*bucket[[:space:]]*[.=]' "$config" 2>/dev/null; then
  warn "$config sets bucket inline or with dotted keys, which this does not edit."
  SKIPPED+=("set bucket.url = \"$url\" in $config by hand")
else
  # Under the lock nico-agent takes for every config write, so none is lost.
  (
    flock 9
    with_url "$config" "$url" >"$config.tmp"
    if cmp -s "$config" "$config.tmp"; then
      rm -f "$config.tmp"
      note "unchanged: bucket.url is $url already"
      exit 0
    fi
    old="$config"
    [[ -f "$old" ]] || old=/dev/null
    diff -u "$old" "$config.tmp" | sed 's/^/      /' || true
    confirm "Write it?" || { rm -f "$config.tmp"; say "left as is"; exit 0; }
    if [[ -x "$bin" ]]; then
      # nico-agent's own parser reads the new file before it replaces the old.
      check=$(mktemp -d)
      mkdir -p "$check/.config/nico-agent"
      cp "$config.tmp" "$check/.config/nico-agent/config.toml"
      if ! refusal=$(HOME="$check" "$bin" repo list); then
        rm -rf "$check" "$config.tmp"
        warn "nico-agent refuses the new config, so $config is left as is:"
        printf '%s\n' "$refusal" | sed 's/^/      /'
        exit 1
      fi
      rm -rf "$check"
    else
      warn "no nico-agent at $bin to check the new config with"
    fi
    mv "$config.tmp" "$config"
    printf '  %s✓ wrote%s bucket.url to %s\n' "$GREEN" "$RESET" "$config"
  ) 9>"$config.lock"
fi

finish
